const DICTS: Record<Lang, Dict> = { uz, ru, en };

interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLang = create<LangState>((set) => ({
  lang: store.get<Lang>('sat_lang', 'uz'),
  setLang: (lang) => {
    store.set('sat_lang', lang);
    document.documentElement.lang = lang;
    set({ lang });
  },
}));

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useLang((s) => s.lang);
  return (key: I18nKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
